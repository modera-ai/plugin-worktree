import { execFile } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import { afterEach, expect, test } from "vitest";
import { applyTaskMerge, previewTaskMerge } from "../src/merge";

const exec = promisify(execFile);
const roots: string[] = [];
afterEach(async () => { for (const path of roots.splice(0)) await rm(path, { recursive: true, force: true }); });

test("merge preview preserves the project; confirmation merges the exact task commit", async () => {
  const root = await mkdtemp(join(tmpdir(), "modera-merge-task-"));
  roots.push(root);
  const source = join(root, "project"), task = join(root, "task");
  await mkdir(source);
  const git = (path: string, ...args: string[]) => exec("git", ["-C", path, ...args]);
  await git(source, "init", "-q");
  await git(source, "config", "user.name", "Test");
  await git(source, "config", "user.email", "test@example.invalid");
  await writeFile(join(source, "file.txt"), "base\n");
  await git(source, "add", ".");
  await git(source, "commit", "-qm", "seed");
  const baseBranch = (await git(source, "branch", "--show-current")).stdout.trim();
  const taskBranch = `modera/task-${"a".repeat(24)}`;
  await git(source, "worktree", "add", "-b", taskBranch, task, "HEAD");
  await writeFile(join(task, "task.txt"), "delivered\n");
  await git(task, "add", ".");
  await git(task, "commit", "-qm", "task work");
  await writeFile(join(source, "project-only.txt"), "already here\n");
  await git(source, "add", ".");
  await git(source, "commit", "-qm", "project work");
  const before = (await git(source, "rev-parse", "HEAD")).stdout.trim();
  const input = { projectPath: source, baseBranch, taskPath: task, expectedTaskBranch: taskBranch };
  const preview = await previewTaskMerge(input);
  expect(preview.sourceHead).toBe(before);
  expect(preview.taskBranch).toBe(taskBranch);
  expect(preview.files).toContain("task.txt");
  expect(preview.commits).toContain("task work");
  expect(preview.changeSummary).toContain("task.txt");
  expect(preview.patch).toContain("+delivered");
  expect(preview.patch).not.toContain("project-only.txt");
  expect(preview.patchTruncated).toBe(false);
  expect((await git(source, "rev-parse", "HEAD")).stdout.trim()).toBe(before);
  await expect(readFile(join(source, "task.txt"), "utf8")).rejects.toThrow();
  const otherBranch = `modera/task-${"f".repeat(24)}`;
  await git(task, "switch", "-c", otherBranch);
  await expect(previewTaskMerge(input)).rejects.toThrow("已切换分支");
  await expect(applyTaskMerge(input, preview)).rejects.toThrow("已切换分支");
  await git(task, "switch", taskBranch);
  const result = await applyTaskMerge(input, preview);
  expect(result.branch).toBe(baseBranch);
  expect(result.commit).not.toBe(before);
  expect((await git(source, "rev-list", "--parents", "-n", "1", "HEAD")).stdout.trim().split(" ")).toHaveLength(3);
  expect((await readFile(join(source, "task.txt"), "utf8")).replace(/\r\n/g, "\n")).toBe("delivered\n");
  await expect(previewTaskMerge(input)).rejects.toThrow("没有尚未合入");
});

test("preview refuses dirty project and conflicts without changing its branch", async () => {
  const root = await mkdtemp(join(tmpdir(), "modera-merge-conflict-"));
  roots.push(root);
  const source = join(root, "project"), task = join(root, "task");
  await mkdir(source);
  const git = (path: string, ...args: string[]) => exec("git", ["-C", path, ...args]);
  await git(source, "init", "-q");
  await git(source, "config", "user.name", "Test");
  await git(source, "config", "user.email", "test@example.invalid");
  await writeFile(join(source, "file.txt"), "base\n");
  await git(source, "add", ".");
  await git(source, "commit", "-qm", "seed");
  const baseBranch = (await git(source, "branch", "--show-current")).stdout.trim();
  await git(source, "worktree", "add", "-b", `modera/task-${"b".repeat(24)}`, task, "HEAD");
  await writeFile(join(task, "file.txt"), "task\n");
  await git(task, "commit", "-qam", "task change");
  await writeFile(join(source, "file.txt"), "source\n");
  await expect(previewTaskMerge({ projectPath: source, baseBranch, taskPath: task, expectedTaskBranch: `modera/task-${"b".repeat(24)}` })).rejects.toThrow("未提交");
  await git(source, "commit", "-qam", "source change");
  const before = (await git(source, "rev-parse", "HEAD")).stdout.trim();
  await expect(previewTaskMerge({ projectPath: source, baseBranch, taskPath: task, expectedTaskBranch: `modera/task-${"b".repeat(24)}` })).rejects.toThrow("合并冲突");
  expect((await git(source, "rev-parse", "HEAD")).stdout.trim()).toBe(before);
  expect((await git(source, "status", "--porcelain")).stdout.trim()).toBe("");
});

test("an archived task branch can still be previewed and merged", async () => {
  const root = await mkdtemp(join(tmpdir(), "modera-merge-archived-"));
  roots.push(root);
  const source = join(root, "project"), task = join(root, "task");
  await mkdir(source);
  const git = (path: string, ...args: string[]) => exec("git", ["-C", path, ...args]);
  await git(source, "init", "-q");
  await git(source, "config", "user.name", "Test");
  await git(source, "config", "user.email", "test@example.invalid");
  await writeFile(join(source, "base.txt"), "base");
  await git(source, "add", ".");
  await git(source, "commit", "-qm", "seed");
  const baseBranch = (await git(source, "branch", "--show-current")).stdout.trim();
  const archivedBranch = `modera/task-${"d".repeat(24)}`;
  await git(source, "worktree", "add", "-b", archivedBranch, task, "HEAD");
  await writeFile(join(task, "archived.txt"), "kept in branch");
  await git(task, "add", ".");
  await git(task, "commit", "-qm", "archived task");
  await git(source, "worktree", "remove", task);
  const input = { projectPath: source, baseBranch, archivedBranch, expectedTaskBranch: archivedBranch };
  const preview = await previewTaskMerge(input);
  expect(preview.taskBranch).toBe(archivedBranch);
  await applyTaskMerge(input, preview);
  expect(await readFile(join(source, "archived.txt"), "utf8")).toBe("kept in branch");
});
